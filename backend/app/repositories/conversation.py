from __future__ import annotations

from typing import Protocol

from app.models.chat import SourceCitation
from app.models.context import RequestContext
from app.models.conversation import ConversationDetail, ConversationSummary


class ConversationRepository(Protocol):
    def create(self, context: RequestContext, title: str) -> ConversationSummary: ...
    def list(self, context: RequestContext) -> list[ConversationSummary]: ...
    def get(self, context: RequestContext, conversation_id: str) -> ConversationDetail | None: ...
    def append_message(
        self, context: RequestContext, conversation_id: str, role: str, content: str,
        sources: list[SourceCitation], run_id: str | None = None,
    ) -> None: ...
    def get_summary(self, context: RequestContext, conversation_id: str) -> tuple[str, int]: ...
    def update_summary(
        self, context: RequestContext, conversation_id: str, summary: str, summarized_through: int
    ) -> None: ...
    def touch(self, context: RequestContext, conversation_id: str) -> None: ...
    def delete(self, context: RequestContext, conversation_id: str) -> bool: ...
